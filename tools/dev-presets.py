#!/usr/bin/env python3
"""dev-presets: generates RemoteCompanion/RCDevEditorPresetsData.h from dev_editor_presets.json
and tools/rc-dev-deliver.py.

    python3 tools/dev-presets.py           # writes header
    python3 tools/dev-presets.py --check   # exit 1 when out of date (build.sh runs this)
"""
import base64
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
VALID_STRATEGIES = {"opencode_api", "antigravity_ext", "clipboard_paste"}


def _objc_escape(s):
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )


def _load_and_validate_presets(presets_path):
    with open(presets_path, "r", encoding="utf-8") as f:
        presets = json.load(f)
    if not isinstance(presets, list) or not presets:
        raise ValueError("dev_editor_presets.json must be a non-empty JSON array")
    seen_ids = set()
    for idx, item in enumerate(presets):
        if not isinstance(item, dict):
            raise ValueError(f"Preset #{idx} must be an object")
        for key in ("id", "name", "strategy"):
            val = item.get(key)
            if not isinstance(val, str) or not val.strip():
                raise ValueError(f"Preset #{idx} missing required string '{key}'")
        pid = item["id"].strip()
        if pid in seen_ids:
            raise ValueError(f"Duplicate preset id: {pid}")
        seen_ids.add(pid)
        if item["strategy"] not in VALID_STRATEGIES:
            raise ValueError(f"Preset '{pid}' has invalid strategy '{item['strategy']}'")
    return presets


def main(check=False):
    presets_path = os.path.join(ROOT, "dev_editor_presets.json")
    deliver_path = os.path.join(ROOT, "tools", "rc-dev-deliver.py")
    header_path = os.path.join(ROOT, "RemoteCompanion", "RCDevEditorPresetsData.h")

    presets = _load_and_validate_presets(presets_path)
    compact_json = json.dumps(presets, separators=(",", ":"), ensure_ascii=False)

    with open(deliver_path, "rb") as f:
        deliver_b64 = base64.b64encode(f.read()).decode("ascii")

    header = (
        "// Generated by tools/dev-presets.py from dev_editor_presets.json and tools/rc-dev-deliver.py; don't edit by hand.\n"
        "#import <Foundation/Foundation.h>\n\n"
        f'static NSString *const kRCDevEditorPresetsJSON = @"{_objc_escape(compact_json)}";\n\n'
        f'static NSString *const kRCDevDeliverPythonScriptB64 = @"{deliver_b64}";\n'
    )

    if check:
        try:
            with open(header_path, "r", encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = ""
        if current != header:
            sys.exit(
                "RemoteCompanion/RCDevEditorPresetsData.h is out of date. "
                "Run: python3 tools/dev-presets.py"
            )
        return

    with open(header_path, "w", encoding="utf-8") as f:
        f.write(header)
    print(f"Generated RCDevEditorPresetsData.h ({len(presets)} presets)")


if __name__ == "__main__":
    main(check="--check" in sys.argv[1:])
