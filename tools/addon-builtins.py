#!/usr/bin/env python3
"""addon-builtins: lists the built-in commands that an add-on command could never get past.

    python3 tools/addon-builtins.py           # writes both
    python3 tools/addon-builtins.py --check   # exit 1 when they're out of date (build.sh runs this)

Built-in commands are tried before add-ons (Tweak.x, handle_command), so an add-on whose
"<id> <command>" starts like a built-in one never runs. This reads handle_command's
[cleanCmd hasPrefix:@"..."] and [cleanCmd isEqualToString:@"..."] tests and writes them to
Tweak/RCAddOnsBuiltins.h (for the loader's check) and into tools/addon-lint.py (between its
BUILTINS markers, when that file is there), so both refuse the same ids. Run it after adding or
renaming a built-in command.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def main(check=False):
    with open(os.path.join(ROOT, "Tweak", "Tweak.x")) as f:
        source = f.read()
    start = source.index("static NSString *handle_command(NSString *cmd) {")
    end = source.index("return RCAddOnsHandleCommand(cleanCmd);", start)
    body = source[start:end]
    # Only lowercase ones matter: add-on commands are lowercase
    prefixes = sorted({p for p in re.findall(r'\[cleanCmd hasPrefix:@"([^"]+)"\]', body) if p == p.lower()})
    commands = sorted({c for c in re.findall(r'\[cleanCmd isEqualToString:@"([^"]+)"\]', body) if c == c.lower() and " " in c})

    def objc(items):
        return ",\n".join("    @\"%s\"" % item.replace("\\", "\\\\").replace('"', '\\"') for item in items)

    header = """// Generated by tools/addon-builtins.py from handle_command in Tweak.x; don't edit by hand.
// Built-in commands are tried before add-ons, so an add-on command that starts with one of these
// prefixes, or is one of these whole commands, never reaches the add-on.

static NSString *const kRCAOBuiltinPrefixes[] = {
%s
};

static NSString *const kRCAOBuiltinCommands[] = {
%s
};
""" % (objc(prefixes), objc(commands))
    header_path = os.path.join(ROOT, "Tweak", "RCAddOnsBuiltins.h")
    lint_path = os.path.join(ROOT, "tools", "addon-lint.py")
    # The Mac checker keeps its own copy, between its BUILTINS markers
    lint = new_lint = None
    if os.path.exists(lint_path):
        with open(lint_path) as f:
            lint = f.read()
        begin, finish = "# BUILTINS (tools/addon-builtins.py writes this)\n", "# END BUILTINS\n"
        block = begin + "BUILTIN_PREFIXES = %r\nBUILTIN_COMMANDS = %r\n" % (prefixes, commands) + finish
        if begin not in lint or finish not in lint:
            sys.exit("addon-lint.py has no BUILTINS markers")
        new_lint = lint[:lint.index(begin)] + block + lint[lint.index(finish) + len(finish):]

    if check:
        try:
            with open(header_path) as f:
                current = f.read()
        except OSError:
            current = ""
        if current != header or new_lint != lint:
            sys.exit("The built-in command list for add-ons is out of date (a built-in command was added or "
                     "renamed in Tweak.x). Run: python3 tools/addon-builtins.py")
        return
    with open(header_path, "w") as f:
        f.write(header)
    if lint is not None:
        with open(lint_path, "w") as f:
            f.write(new_lint)
    print("%d prefixes, %d whole commands" % (len(prefixes), len(commands)))


if __name__ == "__main__":
    main(check="--check" in sys.argv[1:])
